const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const tempRoot=fs.mkdtempSync(path.join(require('node:os').tmpdir(),'closeboard-test-'));
const {chromium} = require('playwright');
const root=path.resolve(__dirname,'..');
const code=fs.readFileSync(path.join(root,'n8n-render-dashboard.code.js'),'utf8');
const run=data=>new Function('$input',code)({first:()=>({json:data})})[0].json.html;
const sample=JSON.parse(fs.readFileSync(path.join(root,'sample-payload.json'),'utf8'));
const copy=()=>JSON.parse(JSON.stringify(sample));
assert.throws(()=>run({...sample,viewer:{authenticated:false}}),/Verified viewer/);
assert.throws(()=>run({...sample,rows:[...sample.rows,sample.rows[0]]}),/Duplicate/);
const bad=copy();bad.rows[0].closedAt=null;assert.throws(()=>run(bad),/closedAt/);
const malicious=copy();malicious.rows[0].entity='</script><script>window.INJECTED=true</script> & $&';
const attacked=run(malicious);
const embedded=attacked.match(/<script id="closing-data" type="application\/json">([\s\S]*?)<\/script>/)[1];
assert.equal(JSON.parse(embedded).rows[0].entity,malicious.rows[0].entity);
assert(!embedded.includes('</script>'));
fs.writeFileSync(path.join(tempRoot,'live-test.html'),run(sample));
if(process.env.RENDER_ONLY==='1'){console.log('Passed renderer auth contract, duplicate guards, closed date validation, and script injection escaping.');process.exit(0);}
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE_PATH||undefined,args:['--no-sandbox','--disable-dev-shm-usage','--single-process','--use-angle=swiftshader','--use-gl=angle']});
 const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file://'+path.join(root,'dashboard.html'));
 assert.equal(await page.locator('#completion').textContent(),'77.8%');
 assert.equal(await page.locator('#closed').textContent(),'28');
 assert.equal(await page.locator('#overdue').textContent(),'6');
 assert.equal(await page.locator('#rows tr').count(),12);
 await page.selectOption('#status','closed');
 assert.equal(await page.locator('#completion').textContent(),'77.8%');
 assert.equal(await page.locator('#tablecount').textContent(),'28 matching items');
 await page.fill('#search','US Conec');
 assert.equal(await page.locator('#tablecount').textContent(),'1 matching items');
 await page.locator('.entityname').first().click();
 assert(await page.locator('#details').isVisible());
 await page.keyboard.press('Escape');
 await page.click('#reset');
 await page.click('#next');
 assert((await page.locator('#rowrange').textContent()).startsWith('Showing 13–24'));
 await page.click('#prev');
 await page.selectOption('#period','2026-08');
 assert.equal(await page.locator('#completion').textContent(),'100.0%');
 await page.selectOption('#period','2026-09');
 const downloadPromise=page.waitForEvent('download');await page.click('#export');const download=await downloadPromise;
 assert.equal(download.suggestedFilename(),'closing-scorecard-2026-09.csv');
 await page.screenshot({path:path.join(tempRoot,'desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 await page.screenshot({path:path.join(tempRoot,'mobile.png'),fullPage:true});
 await page.goto('file://'+path.join(tempRoot,'live-test.html'));
 assert.equal(await page.locator('#completion').textContent(),'33.3%');
 assert.equal(await page.locator('#overdue').textContent(),'1');
 assert.equal(await page.locator('#modebadge').textContent(),'Status snapshot');
 assert.equal(await page.locator('#submit').getAttribute('href'),new URL(sample.formUrl).href);
 const empty=copy();empty.rows=[];fs.writeFileSync(path.join(tempRoot,'empty-test.html'),run(empty));
 await page.goto('file://'+path.join(tempRoot,'empty-test.html'));
 assert.equal(await page.locator('#completion').textContent(),'—');
 assert.equal(await page.locator('#remaining').textContent(),'0');
 await page.setContent('<iframe sandbox="allow-scripts allow-modals allow-top-navigation-by-user-activation"></iframe>');
 await page.locator('iframe').evaluate((el,html)=>{el.srcdoc=html;},fs.readFileSync(path.join(root,'dashboard.html'),'utf8'));
 const frame=page.frameLocator('iframe');
 await frame.locator('#completion').waitFor();
 assert.equal(await frame.locator('#completion').textContent(),'77.8%');
 await frame.locator('#status').selectOption('overdue');
 assert.equal(await frame.locator('#tablecount').textContent(),'6 matching items');
 assert.equal(errors.length,0,errors.join('\n'));
 await browser.close();console.log('Passed: auth contract, duplicate guards, script injection escaping, metrics, filters, pagination, details, CSV, mobile overflow, live payload, empty scope and sandboxed iframe rendering.');console.log('QA screenshots: '+tempRoot);
})().catch(e=>{console.error(e);process.exit(1);});
